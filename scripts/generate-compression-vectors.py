"""Optional fixture generation only: test-side LZO/LZ4, never linked to the app."""
import ctypes, hashlib, json, subprocess
from pathlib import Path
root=Path(__file__).resolve().parents[1]
payload=bytes(range(256))*5
out={'generator':'LZO 2.10 lzo1x_1_compress and LZ4 1.10 LZ4_compress_default (external test tools)', 'payload':payload.hex(),'sha256':hashlib.sha256(payload).hexdigest()}
for library,symbol in [('lzo','lzo1x_1_compress'),('lz4','LZ4_compress_default')]:
 prefix=subprocess.check_output(['brew','--prefix',library],text=True).strip()
 lib=ctypes.CDLL(prefix+'/lib/lib'+('lzo2' if library=='lzo' else 'lz4')+'.dylib')
 source=ctypes.create_string_buffer(payload);target=ctypes.create_string_buffer(4096)
 if library=='lzo':
  fn=getattr(lib,symbol);fn.argtypes=[ctypes.c_void_p,ctypes.c_size_t,ctypes.c_void_p,ctypes.POINTER(ctypes.c_size_t),ctypes.c_void_p];fn.restype=ctypes.c_int
  size=ctypes.c_size_t(4096);work=ctypes.create_string_buffer(1024*1024)
  assert fn(source,len(payload),target,ctypes.byref(size),work)==0
  packed=target.raw[:size.value]
 else:
  fn=getattr(lib,symbol);fn.argtypes=[ctypes.c_void_p,ctypes.c_void_p,ctypes.c_int,ctypes.c_int];fn.restype=ctypes.c_int
  n=fn(source,target,len(payload),4096);assert n>0;packed=target.raw[:n]
 assert len(packed)<len(payload)
 out[library]=packed.hex()
# Data generated by compressors is test payload, not a copy of library source.
(root/'src/testdata/compression_vectors.json').write_text(json.dumps(out,indent=2)+'\n')
(root/'src/testdata/compression_vectors.hpp').write_text('// SPDX-License-Identifier: MPL-2.0\n// Generated by scripts/generate-compression-vectors.py; binary test data only.\n#pragma once\nnamespace compression_vectors {\n'+''.join('inline constexpr const char *'+k+' = "'+out[k]+'";\n' for k in ['payload','lzo','lz4'])+'}\n')
print('Generated independent compressed fixtures:',len(payload),'-> LZO',len(bytes.fromhex(out['lzo'])),'/ LZ4',len(bytes.fromhex(out['lz4'])))
